#include "CHIP_8.h"

#include <algorithm>

constexpr unsigned char FONT[] {
    0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
    0x20, 0x60, 0x20, 0x20, 0x70, // 1
    0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
    0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
    0x90, 0x90, 0xF0, 0x10, 0x10, // 4
    0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
    0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
    0xF0, 0x10, 0x20, 0x40, 0x40, // 7
    0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
    0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
    0xF0, 0x90, 0xF0, 0x90, 0x90, // A
    0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
    0xF0, 0x80, 0x80, 0x80, 0xF0, // C
    0xE0, 0x90, 0x90, 0x90, 0xE0, // D
    0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
    0xF0, 0x80, 0xF0, 0x80, 0x80  // F
};

CHIP_8::CHIP_8() :
PC{0x200}, I {0}, delayTimer{0}, soundTimer{0},
V0{0}, V1{0}, V2{0}, V3{0}, V4{0}, V5{0}, V6{0}, V7{0},
V8{0}, V9{0}, VA{0}, VB{0}, VC{0}, VD{0}, VE{0}, VF{0}
{
    //zero out the ram so there's no garbage data
    for (size_t i = 0; i < 4096; ++i) {
        this->RAM[i] = 0;
    }

    //initialize RAM with font data (apparently convention is 0x050 - 0x09F)
    std::copy_n(FONT, sizeof(FONT), this->RAM + 0x050);

    //Initialize the display (10x hardcoded rendering scale for now, i don't care)
    this->display = sf::RenderWindow(sf::VideoMode({640, 320}), "CHIRP-8");
}